"""Build the result tables of an experiment from its immutable run directories."""

from __future__ import annotations

import csv
import itertools
import json
import re
from collections import Counter
from dataclasses import dataclass, replace
from pathlib import Path

from graph_llm.analysis.lightrag_alignment import AlignmentReport
from graph_llm.analysis.statistics import mcnemar_exact_p_value, wilson_interval
from graph_llm.schemas.question import Question
from graph_llm.schemas.run import Prediction, RunManifest, Score

QUESTION_TYPES = ["L1", "L2", "L3", "L4", "L5"]
ERROR_STAGES = ["output_format", "no_context", "entity_linking", "retrieval", "usage"]
NODE_ID_ANSWER = re.compile(r'"n\d+"')


@dataclass(frozen=True)
class LoadedRun:
    """One run: its manifest and its predictions and scores by question id."""

    manifest: RunManifest
    predictions: dict[str, Prediction]
    scores: dict[str, Score]
    label: str = ""

    @property
    def name(self) -> str:
        """Return the column name: the label if set, otherwise the representation id."""
        return self.label or self.manifest.representation.value


def with_unique_names(runs: list[LoadedRun]) -> list[LoadedRun]:
    """Prefix representation ids with the experiment id when runs of several experiments mix."""
    representations = [run.manifest.representation.value for run in runs]
    if len(set(representations)) == len(representations):
        return runs
    return [
        replace(run, label=f"{run.manifest.experiment_id} {run.manifest.representation.value}")
        for run in runs
    ]


def node_id_answer_count(run: LoadedRun) -> int:
    """Return the number of raw answers that contain a local node id such as "n7"."""
    return sum(bool(NODE_ID_ANSWER.search(p.raw_response)) for p in run.predictions.values())


def load_run(run_directory: Path) -> LoadedRun:
    """Load a run directory."""
    manifest = RunManifest.model_validate_json(
        (run_directory / "manifest.json").read_text(encoding="utf-8")
    )
    predictions = [
        Prediction.model_validate_json(line)
        for line in (run_directory / "predictions.jsonl").read_text(encoding="utf-8").splitlines()
    ]
    scores = [
        Score.model_validate_json(line)
        for line in (run_directory / "scores.jsonl").read_text(encoding="utf-8").splitlines()
    ]
    return LoadedRun(
        manifest=manifest,
        predictions={p.question_id: p for p in predictions},
        scores={s.question_id: s for s in scores},
    )


def percent(value: float) -> str:
    """Format a share as a percentage with one decimal."""
    return f"{100 * value:.1f}"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    """Return a Markdown table."""
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines + [""]


def accuracy_cell(run: LoadedRun, question_ids: list[str]) -> str:
    """Return 'accuracy [low, high]' over a set of questions."""
    correct = sum(run.scores[q].is_correct for q in question_ids)
    low, high = wilson_interval(correct, len(question_ids))
    return f"{percent(correct / len(question_ids))} [{percent(low)}, {percent(high)}]"


def constant_guess_accuracy(questions: list[Question]) -> float:
    """Return the accuracy of always giving the most frequent answer of each template."""
    correct = 0
    by_template: dict[str, list[Question]] = {}
    for question in questions:
        by_template.setdefault(question.template_id, []).append(question)
    for members in by_template.values():
        counts = Counter(
            json.dumps(m.answer.model_dump(exclude={"node_path"}), sort_keys=True) for m in members
        )
        correct += counts.most_common(1)[0][1]
    return correct / len(questions)


def render_report(
    experiment_id: str,
    questions: list[Question],
    runs: list[LoadedRun],
    alignment: AlignmentReport | None,
    index_manifest: dict[str, object] | None,
) -> str:
    """Return all result tables of an experiment as Markdown."""
    runs = with_unique_names(runs)
    ids_by_type = {
        t: [q.question_id for q in questions if q.question_type.value == t] for t in QUESTION_TYPES
    }
    ids_by_template: dict[str, list[str]] = {}
    for question in questions:
        ids_by_template.setdefault(question.template_id, []).append(question.question_id)
    all_ids = [q.question_id for q in questions]
    names = [run.name for run in runs]
    lines = [
        f"# {experiment_id} results",
        "",
        "Generated by `scripts/analyze_experiment.py` from the runs below. Do not edit by hand.",
        "",
        "Runs: " + ", ".join(f"`{run.manifest.run_id}`" for run in runs),
        "",
        "## Benchmark composition",
        "",
    ]
    rows = []
    for template_id, ids in ids_by_template.items():
        members = [q for q in questions if q.question_id in set(ids)]
        rows.append(
            [
                template_id,
                str(len(members)),
                str(sum(q.text != q.template_text for q in members)),
                f"{sum(len(q.evidence.edges) for q in members) / len(members):.1f}",
                f"{sum(q.features.hop_count for q in members) / len(members):.1f}",
                percent(sum(q.features.depends_on_edge_direction for q in members) / len(members)),
            ]
        )
    lines += table(
        [
            "Template",
            "n",
            "Reworded (text differs from template)",
            "Evidence edges (mean)",
            "Hops (mean)",
            "Direction-dependent (%)",
        ],
        rows,
    )
    lines += [
        "## Accuracy by question type",
        "",
        "Accuracy in percent with the 95% Wilson interval. L2 accuracy counts set F1 = 1; "
        "its mean F1 is in the next table.",
        "",
    ]
    guess_rows = []
    for question_type in QUESTION_TYPES:
        members = [q for q in questions if q.question_type.value == question_type]
        guess_rows.append(percent(constant_guess_accuracy(members)))
    rows = []
    for index, question_type in enumerate(QUESTION_TYPES):
        ids = ids_by_type[question_type]
        rows.append(
            [question_type, str(len(ids)), guess_rows[index]]
            + [accuracy_cell(run, ids) for run in runs]
        )
    rows.append(
        ["All", str(len(all_ids)), percent(constant_guess_accuracy(questions))]
        + [accuracy_cell(run, all_ids) for run in runs]
    )
    lines += table(["Type", "n", "Constant guess", *names], rows)

    lines += ["## Mean score by question type", "", "Mean score (L2: set F1).", ""]
    rows = []
    for question_type in QUESTION_TYPES:
        ids = ids_by_type[question_type]
        rows.append(
            [question_type]
            + [percent(sum(run.scores[q].score for q in ids) / len(ids)) for run in runs]
        )
    lines += table(["Type", *names], rows)

    lines += ["## Accuracy by template", ""]
    rows = []
    for template_id, ids in ids_by_template.items():
        rows.append([template_id, str(len(ids))] + [accuracy_cell(run, ids) for run in runs])
    lines += table(["Template", "n", *names], rows)

    lines += [
        "## Paired comparisons",
        "",
        "Exact McNemar p-values on the same questions (exploratory, no correction). "
        "Each cell gives the number of questions only the first / only the second got right, "
        "and the p-value.",
        "",
    ]
    rows = []
    for first, second in itertools.combinations(runs, 2):
        row = [f"{first.name} vs {second.name}"]
        for question_type in [*QUESTION_TYPES, "All"]:
            ids = all_ids if question_type == "All" else ids_by_type[question_type]
            only_first = sum(
                first.scores[q].is_correct and not second.scores[q].is_correct for q in ids
            )
            only_second = sum(
                second.scores[q].is_correct and not first.scores[q].is_correct for q in ids
            )
            p_value = mcnemar_exact_p_value(only_first, only_second)
            row.append(f"{only_first}/{only_second}, p={p_value:.3f}")
        rows.append(row)
    lines += table(["Pair", *QUESTION_TYPES, "All"], rows)

    lines += [
        "## Accuracy on direction-dependent questions",
        "",
        "Questions whose answer changes if edge direction is ignored, against the others.",
        "",
    ]
    dependent = [q.question_id for q in questions if q.features.depends_on_edge_direction]
    independent = [q.question_id for q in questions if not q.features.depends_on_edge_direction]
    lines += table(
        ["Questions", "n", *names],
        [
            ["Direction-dependent", str(len(dependent))]
            + [accuracy_cell(run, dependent) for run in runs],
            ["Not direction-dependent", str(len(independent))]
            + [accuracy_cell(run, independent) for run in runs],
        ],
    )

    lines += [
        "## Evidence recall",
        "",
        "Mean share of the required evidence edges present in the context.",
        "",
    ]
    rows = []
    for question_type in [*QUESTION_TYPES, "All"]:
        ids = all_ids if question_type == "All" else ids_by_type[question_type]
        row = [question_type]
        for run in runs:
            recalls: list[float] = [
                recall for q in ids if (recall := run.scores[q].evidence_recall) is not None
            ]
            row.append(percent(sum(recalls) / len(recalls)) if recalls else "-")
        rows.append(row)
    lines += table(["Type", *names], rows)

    lines += ["## Error stages of wrong answers", "", "Counts over all 250 questions.", ""]
    rows = []
    for run in runs:
        counts = Counter(score.error_stage.value for score in run.scores.values())
        wrong = sum(count for stage, count in counts.items() if stage != "none")
        rows.append([run.name, str(wrong)] + [str(counts.get(stage, 0)) for stage in ERROR_STAGES])
    lines += table(["Representation", "Wrong", *ERROR_STAGES], rows)

    lines += ["### Error stages by question type", ""]
    rows = []
    for run in runs:
        for question_type in QUESTION_TYPES:
            counts = Counter(run.scores[q].error_stage.value for q in ids_by_type[question_type])
            rows.append(
                [run.name, question_type] + [str(counts.get(stage, 0)) for stage in ERROR_STAGES]
            )
    lines += table(["Representation", "Type", *ERROR_STAGES], rows)

    lines += ["## L4 route components", "", "Share of L4 questions.", ""]
    components = [
        "all_streets_known",
        "legal",
        "breaks_direction_or_turn_rule",
        "optimal",
        "sequence_exact",
        "length_within_10_percent",
    ]
    rows = []
    for run in runs:
        row = [run.name]
        for component in components:
            values = [run.scores[q].sub_scores.get(component, 0.0) for q in ids_by_type["L4"]]
            row.append(percent(sum(values) / len(values)))
        rows.append(row)
    lines += table(["Representation", *components], rows)

    lines += ["## Cost per question", ""]
    rows = []
    for run in runs:
        predictions = list(run.predictions.values())
        count = len(predictions)
        context_characters = sum(len(p.context) for p in predictions) / count
        rows.append(
            [
                run.name,
                f"{context_characters:.0f}",
                f"{sum(p.prompt_tokens for p in predictions) / count:.0f}",
                f"{sum(p.completion_tokens for p in predictions) / count:.0f}",
                f"{sum(p.llm_call_count for p in predictions) / count:.2f}",
                f"{sum(p.latency_s for p in predictions) / count:.1f}",
                percent(sum(p.parsed_answer is None for p in predictions) / count),
            ]
        )
    lines += table(
        [
            "Representation",
            "Context characters",
            "Prompt tokens",
            "Completion tokens",
            "LLM calls",
            "Latency (s)",
            "Unparseable (%)",
        ],
        rows,
    )
    lines += [
        'Answers that contain a local node id of the M3 serialization (such as "n7") '
        "instead of a street name: "
        + ", ".join(f"{run.name} {node_id_answer_count(run)}" for run in runs)
        + ".",
        "",
    ]

    if index_manifest is not None:
        lines += ["## M2 index building cost", ""]
        keys = [
            "llm_calls",
            "llm_prompt_tokens",
            "llm_completion_tokens",
            "wall_clock_seconds",
        ]
        lines += table(
            ["Quantity", "Value"], [[key, str(index_manifest.get(key, "-"))] for key in keys]
        )

    if alignment is not None:
        lines += [
            "## M2 knowledge graph against the OSM street graph",
            "",
            "Entities are matched to streets by name. A relation between two street entities "
            "is correct if the streets meet in OSM.",
            "",
        ]
        lines += table(
            ["Quantity", "Value"],
            [[name, str(value)] for name, value in alignment.model_dump().items()],
        )
    return "\n".join(lines)


def write_per_question_table(path: Path, questions: list[Question], runs: list[LoadedRun]) -> None:
    """Write one row per question with its features and every run's outcome and cost.

    This is the table later method design (RQ4) starts from.
    """
    header = [
        "question_id",
        "question_type",
        "template_id",
        "hop_count",
        "requires_computation",
        "depends_on_edge_direction",
    ]
    for run in runs:
        header += [
            f"{run.name}_correct",
            f"{run.name}_score",
            f"{run.name}_evidence_recall",
            f"{run.name}_error_stage",
            f"{run.name}_prompt_tokens",
            f"{run.name}_latency_s",
        ]
    with path.open("w", encoding="utf-8", newline="") as file:
        writer = csv.writer(file)
        writer.writerow(header)
        for question in questions:
            row: list[object] = [
                question.question_id,
                question.question_type.value,
                question.template_id,
                question.features.hop_count,
                question.features.requires_computation,
                question.features.depends_on_edge_direction,
            ]
            for run in runs:
                score = run.scores[question.question_id]
                prediction = run.predictions[question.question_id]
                row += [
                    int(score.is_correct),
                    f"{score.score:.4f}",
                    "" if score.evidence_recall is None else f"{score.evidence_recall:.4f}",
                    score.error_stage.value,
                    prediction.prompt_tokens,
                    f"{prediction.latency_s:.2f}",
                ]
            writer.writerow(row)
