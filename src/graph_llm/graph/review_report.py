"""Render the graph review cards and decisions as a Markdown report."""

from __future__ import annotations

from collections import Counter
from collections.abc import Mapping, Sequence

from graph_llm.schemas.review import JunctionCard, ReviewDecision, StreetCard

FLAG_DESCRIPTIONS = {
    "S-MIXED": "Street is neither fully one-way nor fully two-way (with or without median).",
    "S-DIVIDED-IMBALANCE": "The two carriageways of the divided parts differ a lot in length.",
    "S-PIECES": "The street's edges form several pieces even with junctions contracted.",
    "S-INNER-DEAD-END": "The street has a dead end that is not at the area boundary.",
    "S-SHORT": "Centre line shorter than 60 m.",
    "S-SHARED-NAME": "Another street in the area has the same name.",
    "S-MULTI-NAME-EDGES": "Some edges carry several names (merged OSM ways).",
    "S-ISOLATED": "Meets no other regular street.",
    "J-WIDE": "Junction nodes spread over more than 60 m.",
    "J-MANY-NODES": "Junction has six or more nodes.",
    "J-PLACE-SPLIT": "A named square or roundabout forms several junctions.",
    "J-CONNECTORS": "Unnamed connecting edges join nodes over more than 30 m.",
    "J-MEET-WITHOUT-SHARED-NODE": "Streets meet here without sharing a node (new in graph v2).",
    "J-UNMAPPED-RESTRICTION": "A car turn restriction here could not be mapped onto edges.",
}


def map_link(map_file: str, latitude: float, longitude: float, zoom: int = 18) -> str:
    """Return a link that opens the interactive map at a location."""
    return f"[map]({map_file}#{latitude:.5f},{longitude:.5f},{zoom})"


def cell(text: str) -> str:
    """Escape a value for a Markdown table cell."""
    return text.replace("|", "/").replace("\n", " ")


def decision_text(decisions: Mapping[str, ReviewDecision], item_id: str) -> str:
    """Return the recorded decision of a card, or 'not reviewed'."""
    decision = decisions.get(item_id)
    if decision is None:
        return "not reviewed"
    return f"{decision.decision.value}: {decision.reason}"


def render_review_report(
    graph_version: str,
    street_cards: Sequence[StreetCard],
    junction_cards: Sequence[JunctionCard],
    decisions: Mapping[str, ReviewDecision],
    map_file: str,
) -> str:
    """Return the review report of one graph version."""
    lines = [
        f"# Graph review: {graph_version}",
        "",
        "Generated by `scripts/build_reference_graph.py`. Do not edit by hand. Review decisions "
        "come from "
        f"`configs/graphs/{graph_version}_review.yaml`.",
        "",
        "## Summary",
        "",
        "| Item | Cards | Flagged | Reviewed |",
        "|---|---|---|---|",
        f"| Regular streets | {len(street_cards)} | {sum(bool(c.flags) for c in street_cards)} | "
        f"{sum(c.street_id in decisions for c in street_cards)} |",
        f"| Junctions of regular streets | {len(junction_cards)} | "
        f"{sum(bool(c.flags) for c in junction_cards)} | "
        f"{sum(c.junction_id in decisions for c in junction_cards)} |",
        "",
        "| Flag | Meaning | Count |",
        "|---|---|---|",
    ]
    counts = Counter(f.code for c in street_cards for f in c.flags)
    counts.update(f.code for j in junction_cards for f in j.flags)
    for code, description in FLAG_DESCRIPTIONS.items():
        lines.append(f"| {code} | {description} | {counts.get(code, 0)} |")
    directions = Counter(c.direction for c in street_cards)
    lines += [
        "",
        "Street direction status: "
        + ", ".join(f"{name} {count}" for name, count in sorted(directions.items()))
        + ".",
        "",
        "## Flagged streets",
        "",
    ]
    for card in street_cards:
        if not card.flags:
            continue
        lines += [
            f"### {card.name} (`{card.street_id}`)",
            "",
            f"- Direction: {card.direction}; centre line {card.centre_line_length_m:.0f} m "
            f"(two-way {card.two_way_length_m:.0f}, divided {card.divided_length_m:.0f}, "
            f"one-way {card.one_way_length_m:.0f}); "
            + map_link(map_file, card.latitude, card.longitude, 17),
            f"- Meets: {', '.join(card.meeting_street_names) or '-'}"
            + (f"; places: {', '.join(card.places)}" if card.places else ""),
            *[f"- **{flag.code}**: {flag.message}" for flag in card.flags],
            f"- Review: {decision_text(decisions, card.street_id)}",
            "",
        ]
    lines += ["## Flagged junctions", ""]
    for junction in junction_cards:
        if not junction.flags:
            continue
        title = ", ".join(junction.place_names) or " / ".join(junction.regular_street_names[:4])
        lines += [
            f"### {title} (`{junction.junction_id}`)",
            "",
            f"- Kind: {junction.kind}; {junction.node_count} nodes over {junction.spread_m:.0f} m; "
            + map_link(map_file, junction.latitude, junction.longitude),
            f"- Streets: {', '.join(junction.regular_street_names)}",
            f"- Car restrictions: {junction.unconditional_car_restrictions} always, "
            f"{junction.conditional_car_restrictions} timed, "
            f"{junction.unmapped_restrictions} unmapped",
            *[f"- **{flag.code}**: {flag.message}" for flag in junction.flags],
            f"- Review: {decision_text(decisions, junction.junction_id)}",
            "",
        ]
    lines += [
        "## Unflagged streets",
        "",
        "| Street | Direction | Centre line (m) | Meets | Review | Map |",
        "|---|---|---|---|---|---|",
    ]
    for card in street_cards:
        if card.flags:
            continue
        lines.append(
            f"| {cell(card.name)} | {card.direction} | {card.centre_line_length_m:.0f} | "
            f"{cell(', '.join(card.meeting_street_names))} | "
            f"{cell(decision_text(decisions, card.street_id))} | "
            f"{map_link(map_file, card.latitude, card.longitude, 17)} |"
        )
    lines += [
        "",
        "## Unflagged junctions",
        "",
        "| Junction | Kind | Nodes | Streets | Restrictions (always/timed) | Review | Map |",
        "|---|---|---|---|---|---|---|",
    ]
    for junction in junction_cards:
        if junction.flags:
            continue
        lines.append(
            f"| `{junction.junction_id}` | {junction.kind} | {junction.node_count} | "
            f"{cell(', '.join(junction.regular_street_names))} | "
            f"{junction.unconditional_car_restrictions}/{junction.conditional_car_restrictions} | "
            f"{cell(decision_text(decisions, junction.junction_id))} | "
            f"{map_link(map_file, junction.latitude, junction.longitude)} |"
        )
    return "\n".join(lines) + "\n"
