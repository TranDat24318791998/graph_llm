"""Measure how completely the OSM edge attributes are filled in for a graph."""

import math
from collections import Counter

from graph_llm.graph.types import RoadGraph
from graph_llm.schemas.graph import AttributeCoverage, CoverageReport

SURVEYED_ATTRIBUTES: tuple[str, ...] = (
    "name",
    "highway",
    "oneway",
    "length",
    "lanes",
    "maxspeed",
    "ref",
    "bridge",
    "tunnel",
    "junction",
    "access",
    "width",
)


def has_value(value: object) -> bool:
    """Return True if an attribute value carries information.

    A missing key, None, an empty string, an empty list and NaN all count as
    "no value".
    """
    if value is None:
        return False
    if isinstance(value, float) and math.isnan(value):
        return False
    if isinstance(value, str | list):
        return len(value) > 0
    return True


def as_list(value: object) -> list[object]:
    """Return a value as a list, so single and multi-valued attributes are handled alike."""
    if isinstance(value, list):
        return value
    return [value]


def compute_attribute_coverage(
    edge_attributes: list[dict[str, object]], attribute: str, total_length_m: float
) -> AttributeCoverage:
    """Compute the coverage of one attribute over all edges."""
    edges_with_value = 0
    length_with_value_m = 0.0
    multi_valued_edges = 0

    for attributes in edge_attributes:
        value = attributes.get(attribute)
        if not has_value(value):
            continue
        edges_with_value += 1
        length_with_value_m += edge_length_m(attributes)
        if isinstance(value, list):
            multi_valued_edges += 1

    edge_count = len(edge_attributes)
    return AttributeCoverage(
        attribute=attribute,
        edges_with_value=edges_with_value,
        edge_share=edges_with_value / edge_count if edge_count > 0 else 0.0,
        # Summing the same lengths in a different order can exceed the total by a
        # floating-point rounding error, so the share is capped at 1.0.
        length_share=min(length_with_value_m / total_length_m, 1.0) if total_length_m > 0 else 0.0,
        multi_valued_edges=multi_valued_edges,
    )


def edge_length_m(attributes: dict[str, object]) -> float:
    """Return the length of an edge in metres, or 0.0 if it has none."""
    length = attributes.get("length")
    if isinstance(length, int | float) and not math.isnan(length):
        return float(length)
    return 0.0


def compute_coverage_report(graph: RoadGraph, area_id: str) -> CoverageReport:
    """Compute attribute coverage and basic statistics for a road graph."""
    edge_attributes: list[dict[str, object]] = [
        attributes for _, _, attributes in graph.edges(data=True)
    ]
    total_length_m = sum(edge_length_m(attributes) for attributes in edge_attributes)

    street_names: set[str] = set()
    highway_class_counts: Counter[str] = Counter()
    oneway_edge_count = 0

    for attributes in edge_attributes:
        name = attributes.get("name")
        if has_value(name):
            street_names.update(str(single_name) for single_name in as_list(name))

        highway = attributes.get("highway")
        if has_value(highway):
            highway_class_counts.update(str(single_class) for single_class in as_list(highway))

        if attributes.get("oneway") is True:
            oneway_edge_count += 1

    return CoverageReport(
        area_id=area_id,
        node_count=graph.number_of_nodes(),
        edge_count=len(edge_attributes),
        total_length_m=total_length_m,
        oneway_edge_count=oneway_edge_count,
        distinct_street_name_count=len(street_names),
        attributes=[
            compute_attribute_coverage(edge_attributes, attribute, total_length_m)
            for attribute in SURVEYED_ATTRIBUTES
        ],
        highway_class_edge_counts=dict(highway_class_counts.most_common()),
    )


def render_coverage_markdown(report: CoverageReport) -> str:
    """Render a coverage report as a Markdown document."""
    lines = [
        f"# OSM Attribute Coverage: {report.area_id}",
        "",
        "Generated by `scripts/survey_coverage.py`. Do not edit by hand.",
        "",
        "## Graph size",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| Nodes | {report.node_count} |",
        f"| Directed edges | {report.edge_count} |",
        f"| Total edge length | {report.total_length_m / 1000:.1f} km |",
        f"| Edges flagged one-way | {report.oneway_edge_count} |",
        f"| Distinct street names | {report.distinct_street_name_count} |",
        "",
        "## Attribute coverage",
        "",
        "An edge counts as covered if the attribute has a non-empty value. "
        "Multi-valued edges carry a list of values, because graph simplification "
        "merged consecutive segments whose values differ.",
        "",
        "`oneway` and `length` are always filled in by OSMnx: a way without a "
        "`oneway` tag is stored as two-way, and `length` is computed from the "
        "geometry. Their coverage therefore says nothing about how completely "
        "these properties are tagged in OpenStreetMap.",
        "",
        "| Attribute | Edges with value | Share of edges | Share of length | Multi-valued edges |",
        "|---|---|---|---|---|",
    ]
    for coverage in report.attributes:
        lines.append(
            f"| `{coverage.attribute}` | {coverage.edges_with_value} "
            f"| {coverage.edge_share:.1%} | {coverage.length_share:.1%} "
            f"| {coverage.multi_valued_edges} |"
        )

    lines += [
        "",
        "## Road classes",
        "",
        "| `highway` value | Edges |",
        "|---|---|",
    ]
    for highway_class, edge_count in report.highway_class_edge_counts.items():
        lines.append(f"| `{highway_class}` | {edge_count} |")

    return "\n".join(lines) + "\n"
