"""Render a Markdown report of a processed graph, for review by the owner."""

from collections import Counter

from graph_llm.names.normalize import name_key
from graph_llm.schemas.street import ProcessedGraphMetadata, Street, StreetCategory


def render_street_model_markdown(metadata: ProcessedGraphMetadata, streets: list[Street]) -> str:
    """Return the report of the road layer and the street layer as Markdown."""
    config = metadata.config
    source = metadata.source_snapshot
    category_counts = Counter(street.category for street in streets)
    askable_count = sum(
        1
        for street in streets
        if street.category is StreetCategory.REGULAR and not street.shares_name_with_other_street
    )
    reason_by_key = {
        name_key(override.name): override.reason for override in config.street_overrides
    }

    lines = [
        f"# Street Model: {config.graph_version}",
        "",
        "Generated by `scripts/build_graph.py`. Do not edit by hand.",
        "",
        "## Source",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| Snapshot | `{source.area.area_id}`, downloaded {source.downloaded_at:%Y-%m-%d} |",
        f"| Snapshot GraphML sha256 | `{source.graphml_sha256}` |",
        f"| Processed GraphML sha256 | `{metadata.graphml_sha256}` |",
        f"| Streets file sha256 | `{metadata.streets_sha256}` |",
        "",
        "## Road layer",
        "",
        "The OSM graph reduced to its largest strongly connected component, so every node "
        "can reach every other node along legal edge directions. No edge is added or changed.",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| Nodes | {metadata.node_count} |",
        f"| Directed edges | {metadata.edge_count} |",
        f"| Removed nodes | {len(metadata.removed_node_ids)} |",
        f"| Removed edges | {metadata.removed_edge_count} |",
        f"| Edges without a name | {metadata.unnamed_edge_count} |",
        "",
        "## Street layer",
        "",
        f"Pieces of one name are joined automatically when a path of at most "
        f"{config.merge_gap_m:.0f} m connects them, ignoring edge direction. Names left in "
        "several groups are decided by a reviewed override.",
        "",
        "| Category | Streets |",
        "|---|---|",
        f"| Regular | {category_counts[StreetCategory.REGULAR]} |",
        f"| Alley | {category_counts[StreetCategory.ALLEY]} |",
        f"| Internal road | {category_counts[StreetCategory.INTERNAL]} |",
        f"| Total | {len(streets)} |",
        f"| Regular streets with an unambiguous name (askable in Phase 1) | {askable_count} |",
        "",
        "### Names stored in several pieces",
        "",
        "| Name key | Pieces | Groups after automatic rule | Decision | Streets | Reason |",
        "|---|---|---|---|---|---|",
    ]
    for resolution in sorted(
        metadata.name_resolutions, key=lambda item: (item.override is None, item.name_key)
    ):
        decision = resolution.override.value if resolution.override else "automatic"
        lines.append(
            f"| {resolution.name_key} | {resolution.piece_count} | "
            f"{resolution.groups_after_automatic_rule} | {decision} | "
            f"{', '.join(resolution.street_ids)} | {reason_by_key.get(resolution.name_key, '')} |"
        )

    lines += [
        "",
        "### Streets with several OSM spellings",
        "",
        "| Street | OSM spellings |",
        "|---|---|",
    ]
    for street in streets:
        if len(street.osm_names) > 1:
            lines.append(f"| {street.street_id} | {', '.join(street.osm_names)} |")

    lines += ["", "### Aliases", "", "| Street | Aliases |", "|---|---|"]
    for street in streets:
        if street.aliases:
            lines.append(f"| {street.display_name} | {', '.join(street.aliases)} |")

    lines += ["", "### Internal roads", ""]
    internal_names = sorted(
        street.display_name for street in streets if street.category is StreetCategory.INTERNAL
    )
    lines.append(", ".join(internal_names))
    lines.append("")
    return "\n".join(lines)
